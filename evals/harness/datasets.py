"""Sync the eval tracks into their Opik datasets (ADR-0022 §6; ADR-0017 §2,6).

The Opik datasets are the axes every ``evaluate()`` run scores against. ``decode-benchmark-v2`` gets
one item per Benchmark Task — its key, its slice labels, the prompt VERBATIM and a ``checksum`` over
the whole task folder; ``decode-regression-v1`` gets one item per behavior probe (``probe_id`` /
``tags``). The heavy assets (``environment/``, ``tests/``, ``solution/``, probe fixtures) stay on
disk; the item only needs what a human filters and sorts an Experiment by.

The ``checksum`` is the item's version marker. Opik dedupes an ``insert`` by CONTENT hash, so a task
whose folder is unchanged re-syncs to the same item, while an EDITED task mints a new item beside the
old one (Opik never deletes the stale one). A Benchmark Job therefore selects the item whose checksum
matches what is on disk right now (``evals.harness.benchmark``) — without it, one ``--task`` run
would evaluate every historical version of that task.

Dataset names are code constants, not settings (ADR-0017 §2) — a suite version is a property of the
suite, not an operator knob. Both syncs are idempotent: ``get_or_create`` never duplicates the dataset
and Opik ``insert`` deduplicates items by content, so re-running is safe. ``opik`` is imported at this
module's scope on purpose — the ``python -m evals`` CLI stays opik-free by importing this module lazily,
only inside the ``sync`` command (ADR-0017 §1).
"""

from __future__ import annotations

import hashlib
from collections.abc import Iterable, Iterator, Sequence
from pathlib import Path
from typing import TYPE_CHECKING, Any

import opik

from decode.config.settings import settings
from evals.harness.task_loader import BenchmarkTask

if TYPE_CHECKING:
    from opik.api_objects.dataset.dataset import Dataset

    from evals.regression.probe import RegressionProbe

# The single benchmark dataset version (ADR-0022 §6). Bumping the suite bumps this constant; v2 is
# the format-v2 Benchmark Task (``task.toml`` + ``instruction.md`` + ``tests/test.sh``).
BENCHMARK_DATASET_NAME = "decode-benchmark-v2"

# Generated bytecode is an artifact of RUNNING a task's python, not part of the task's identity —
# hashing it would make a checksum depend on whether the oracle gate happened to run first.
CHECKSUM_IGNORED_DIR_NAMES = frozenset({"__pycache__"})
CHECKSUM_IGNORED_SUFFIXES = (".pyc",)

# The single regression-probe dataset version (ADR-0017 §6). Bumping the suite bumps this constant.
REGRESSION_DATASET_NAME = "decode-regression-v1"


def benchmark_dataset_item(task: BenchmarkTask) -> dict[str, Any]:
    """The Opik dataset item for one task: keys, slice labels, prompt and checksum (ADR-0022 §6).

    ``instruction`` rides along so the Experiment UI shows what the agent was actually asked without
    a checkout, and ``checksum`` versions the item (see the module docstring). ``tags`` is copied
    into a fresh list so the item never aliases the task's mutable field.
    """
    return {
        "task_id": task.id,
        "difficulty": task.difficulty,
        "category": task.category,
        "tags": list(task.tags),
        "instruction": task.instruction,
        "checksum": task_checksum(task),
    }


def task_checksum(task: BenchmarkTask) -> str:
    """sha256 over every file in the task folder, in sorted relative-path order (ADR-0022 §6).

    The relative path is hashed with the bytes (and both are ``\0``-terminated), so a pure rename —
    or a file moved between ``environment/`` and ``solution/`` — changes the checksum just like an
    edit does. Deterministic across machines: the walk is sorted by POSIX relative path and
    ``__pycache__`` / ``*.pyc`` are skipped.
    """
    digest = hashlib.sha256()
    for path, relative in _checksummed_files(task.task_dir):
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def _checksummed_files(task_dir: Path) -> Iterator[tuple[Path, str]]:
    """Every hashed file of a task folder as ``(path, relative posix path)``, sorted by the latter."""
    files = [
        (path, path.relative_to(task_dir).as_posix())
        for path in task_dir.rglob("*")
        if path.is_file() and not _is_generated(path.relative_to(task_dir))
    ]
    yield from sorted(files, key=lambda pair: pair[1])


def _is_generated(relative: Path) -> bool:
    """True for build artifacts a checksum must ignore (``__pycache__/`` trees, ``*.pyc``)."""
    return bool(CHECKSUM_IGNORED_DIR_NAMES.intersection(relative.parts)) or relative.suffix in (
        CHECKSUM_IGNORED_SUFFIXES
    )


def sync_benchmark_dataset(
    tasks: Iterable[BenchmarkTask], *, client: opik.Opik | None = None
) -> Dataset:
    """Upsert one dataset item per task into ``decode-benchmark-v2`` (ADR-0022 §6).

    Uses ``get_or_create_dataset`` (never duplicates the dataset) and a single ``insert`` of all
    items (Opik deduplicates by content, so re-syncing is idempotent). Pass ``client`` to inject a
    stub in tests; the default constructs a real :class:`opik.Opik`, which needs Opik config. An
    empty ``tasks`` is a valid no-op sync. An EDITED task lands as a new item beside its stale
    predecessor (Opik never deletes); the ``checksum`` is what tells the two apart at run time.
    Returns the Opik ``Dataset`` handle.

    The dataset is created IN ``settings.eval_project_name``: opik 2.2.36 resolves an
    ``evaluate()`` run's project from the DATASET (``evaluate(project_name=...)`` is deprecated and
    ignored when the dataset has one), so a dataset with no project sends every benchmark trace to
    an auto-named project instead of ``decode-evals`` — which is how a run "logged under
    decode-evals" ends up nowhere near it.
    """
    client = client or opik.Opik()
    dataset = client.get_or_create_dataset(
        BENCHMARK_DATASET_NAME, project_name=settings.eval_project_name
    )
    items: Sequence[dict[str, Any]] = [benchmark_dataset_item(task) for task in tasks]
    if items:
        dataset.insert(items)
    return dataset


def regression_dataset_item(probe: RegressionProbe) -> dict[str, Any]:
    """The Opik dataset item for one probe: its key plus the slice tags (ADR-0017 §6).

    ``tags`` is copied into a fresh list so the item never aliases the probe's mutable field.
    """
    return {"probe_id": probe.id, "tags": list(probe.tags)}


def sync_regression_dataset(
    probes: Iterable[RegressionProbe], *, client: opik.Opik | None = None
) -> Dataset:
    """Upsert one dataset item per probe into ``decode-regression-v1`` (ADR-0017 §6).

    Uses ``get_or_create_dataset`` (never duplicates the dataset) and a single ``insert`` of all items
    (Opik deduplicates by content, so re-syncing is idempotent). Pass ``client`` to inject a stub in
    tests; the default constructs a real :class:`opik.Opik`, which needs Opik config. An empty
    ``probes`` is a valid no-op sync. Returns the Opik ``Dataset`` handle.
    """
    client = client or opik.Opik()
    dataset = client.get_or_create_dataset(REGRESSION_DATASET_NAME)
    items: Sequence[dict[str, Any]] = [regression_dataset_item(probe) for probe in probes]
    if items:
        dataset.insert(items)
    return dataset
